CREATE TABLE IF NOT EXISTS meeting_room (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, room_name VARCHAR(100), capacity INT,
 equipment VARCHAR(500), status INT, is_deleted INT DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS booking_order (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, user_id BIGINT NOT NULL, room_id BIGINT NOT NULL,
 topic VARCHAR(200), start_time TIMESTAMP NOT NULL, end_time TIMESTAMP NOT NULL, status INT,
 request_id VARCHAR(64), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uk_booking_request UNIQUE(user_id, request_id)
);
